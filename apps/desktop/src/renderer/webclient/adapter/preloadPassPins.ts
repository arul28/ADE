/** Guards every namespace of the web surface named in the table above. */
export function guardPreloadPassPinnedMembers(
  surface: Record<string, unknown>,
  scope: RuntimePinScope,
): void {
  for (const [namespace, pinArgIndex] of Object.entries(PRELOAD_PASS_PINNED_MEMBERS)) {
    const members = surface[namespace];
    if (!members || typeof members !== "object") continue;
    guardPinnedMembers(members, namespace, pinArgIndex, scope);
  }
}
