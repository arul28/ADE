#!/usr/bin/env node
/**
 * Generates the settings catalog the iOS chat reads to label settings chips.
 *
 *   node apps/desktop/scripts/generate-ios-settings-catalog.mjs           write the catalog
 *   node apps/desktop/scripts/generate-ios-settings-catalog.mjs --check   exit 1 when the checked-in catalog is stale
 *
 * A settings chip (`ade://settings/<id>`) and a page chip (`ade://open/<place>`)
 * are labelled from ADE's own lists, never from the agent's text. Those lists
 * live in `src/shared/settingsManifest.ts`, `settingsAgentAccess.ts` and
 * `openPlaces.ts`; iOS cannot run TypeScript, so this script writes their
 * labels to `apps/ios/ADE/Views/Work/WorkSettingsCatalog.swift`.
 *
 * Run it after adding, moving or renaming a setting, and commit the result.
 * `--check` is the drift guard; CI runs it (the `lint-desktop` job).
 */
import { build } from "esbuild";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const desktopRoot = path.resolve(here, "..");
const catalogPath = path.resolve(desktopRoot, "../ios/ADE/Views/Work/WorkSettingsCatalog.swift");

async function loadLists() {
  const dir = mkdtempSync(path.join(tmpdir(), "ade-ios-settings-catalog-"));
  const outfile = path.join(dir, "settingsCatalog.mjs");
  try {
    await build({
      stdin: {
        contents: [
          'export { SETTINGS_ENTRIES, settingsEntryLabelPath } from "./settingsManifest";',
          'export { settingAgentAccess } from "./settingsAgentAccess";',
          'export { OPEN_PLACES } from "./openPlaces";',
        ].join("\n"),
        resolveDir: path.join(desktopRoot, "src/shared"),
        loader: "ts",
      },
      bundle: true,
      format: "esm",
      platform: "node",
      outfile,
      logLevel: "silent",
    });
    return await import(pathToFileURL(outfile).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function swiftString(value) {
  return JSON.stringify(value);
}

function render({ SETTINGS_ENTRIES, settingsEntryLabelPath, settingAgentAccess, OPEN_PLACES }) {
  const settings = SETTINGS_ENTRIES.map((entry) => {
    const access = settingAgentAccess(entry.id);
    const locked = access.agent === "owner-only" && access.reason !== "preference";
    return `    ${swiftString(entry.id)}: Setting(path: ${swiftString(settingsEntryLabelPath(entry).join(" › "))}, locked: ${locked}),`;
  });
  const places = OPEN_PLACES.map((place) => `    ${swiftString(place.id)}: ${swiftString(place.label)},`);
  return `// GENERATED by apps/desktop/scripts/generate-ios-settings-catalog.mjs. Do not edit.
//
// Labels for settings chips (\`ade://settings/<id>\`) and page chips
// (\`ade://open/<place>\`), from the desktop's own lists. A chip's label comes
// from here, never from the agent's text.

import Foundation

enum WorkSettingsCatalog {
  struct Setting: Equatable {
    /// Where the setting sits, as the desktop sidebar names it.
    let path: String
    /// Guards the user's work (publishing, sign-ins, money…): only the user changes it.
    let locked: Bool
  }

  static let settings: [String: Setting] = [
${settings.join("\n")}
  ]

  static let places: [String: String] = [
${places.join("\n")}
  ]
}
`;
}

const lists = await loadLists();
const next = render(lists);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(catalogPath, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== next) {
    console.error(`${path.relative(process.cwd(), catalogPath)} is stale. Run: node apps/desktop/scripts/generate-ios-settings-catalog.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(catalogPath, next);
  console.log(`wrote ${path.relative(process.cwd(), catalogPath)}`);
}
