#!/usr/bin/env node
"use strict";

const path = require("path");
const fs = require("fs");
const { spawnSync } = require("child_process");

const SUBCOMMANDS = [
  "auth",
  "doctor",
  "lanes",
  "git",
  "diff",
  "files",
  "prs",
  "run",
  "shell",
  "chat",
  "agent",
  "cto",
  "linear",
  "automations",
  "coordinator",
  "tests",
  "proof",
  "ios-sim",
  "memory",
  "settings",
  "actions",
  "cursor",
];

const repoRoot = path.resolve(__dirname, "..", "..", "..");
const cliPath = path.resolve(repoRoot, "apps", "ade-cli", "dist", "cli.cjs");
const outDir = path.resolve(__dirname, "..", "resources");
const outPath = path.join(outDir, "ade-cli-help.txt");

function runHelp(args) {
  const res = spawnSync(process.execPath, [cliPath, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    timeout: 15000,
  });
  if (res.error) return null;
  const out = `${res.stdout || ""}${res.stderr || ""}`.trim();
  return out.length > 0 ? out : null;
}

function main() {
  if (!fs.existsSync(cliPath)) {
    fs.mkdirSync(outDir, { recursive: true });
    const stub = [
      "# ADE CLI help digest",
      "# TODO: ade-cli dist/cli.cjs not found at build time; rebuild ade-cli and rerun `npm run regen-cli-help`.",
      "",
    ].join("\n");
    fs.writeFileSync(outPath, stub, "utf8");
    process.stderr.write(`[regen-ade-cli-help] cli not found at ${cliPath}; wrote stub.\n`);
    return;
  }
  fs.mkdirSync(outDir, { recursive: true });
  const parts = [];
  parts.push("# ADE CLI help digest");
  parts.push(`# Generated by apps/desktop/scripts/regen-ade-cli-help.cjs`);
  parts.push("");
  const root = runHelp(["--help"]);
  if (root) {
    parts.push("## ade --help");
    parts.push(root);
    parts.push("");
  }
  for (const sub of SUBCOMMANDS) {
    const text = runHelp([sub, "--help"]);
    if (!text) continue;
    parts.push(`## ade ${sub} --help`);
    parts.push(text);
    parts.push("");
  }
  fs.writeFileSync(outPath, parts.join("\n"), "utf8");
  process.stderr.write(`[regen-ade-cli-help] wrote ${outPath} (${parts.length} sections)\n`);
}

main();
