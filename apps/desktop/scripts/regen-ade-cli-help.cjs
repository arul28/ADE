#!/usr/bin/env node
"use strict";

const path = require("path");
const fs = require("fs");
const os = require("os");
const { spawnSync } = require("child_process");

const SUBCOMMANDS = [
  "auth",
  "doctor",
  "triage",
  "skill",
  "lanes",
  "git",
  "diff",
  "files",
  "search",
  "prs",
  "shell",
  "terminal",
  "chat",
  "cto",
  "linear",
  "automations",
  "flow",
  "tests",
  "proof",
  "ios-sim",
  "android",
  "app-control",
  "devices",
  "browser",
  "settings",
  "update",
  "actions",
  "cursor",
];

const repoRoot = path.resolve(__dirname, "..", "..", "..");
const cliPath = path.resolve(repoRoot, "apps", "ade-cli", "dist", "cli.cjs");
const outDir = path.resolve(__dirname, "..", "resources");
const outPath = path.join(outDir, "ade-cli-help.txt");

/**
 * Help changes with what this machine's brain answers (an account with ADE
 * Cloud gets more lines). The digest is the help of a machine with no brain
 * and no account, so it is the same on every machine and in CI.
 */
function isolatedEnv() {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "ade-cli-help-"));
  const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith("ADE_")));
  return { home, env: { ...env, HOME: home, USERPROFILE: home } };
}

const isolated = isolatedEnv();

function runHelp(args) {
  const res = spawnSync(process.execPath, [cliPath, ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    timeout: 15000,
    env: isolated.env,
  });
  if (res.error) return null;
  const out = `${res.stdout || ""}${res.stderr || ""}`.trim();
  return out.length > 0 ? out : null;
}

function buildDigest() {
  if (!fs.existsSync(cliPath)) {
    throw new Error(
      `[regen-ade-cli-help] missing ${cliPath}. Run \`npm --prefix apps/ade-cli run build\` first.`,
    );
  }
  const parts = [];
  parts.push("# ADE CLI help digest");
  parts.push(`# Generated by apps/desktop/scripts/regen-ade-cli-help.cjs`);
  parts.push("");
  const root = runHelp(["--help"]);
  if (root) {
    parts.push("## ade --help");
    parts.push(root);
    parts.push("");
  }
  for (const sub of SUBCOMMANDS) {
    const text = runHelp([sub, "--help"]);
    if (!text) continue;
    parts.push(`## ade ${sub} --help`);
    parts.push(text);
    parts.push("");
  }
  return { parts, content: parts.join("\n") };
}

/** Where the committed digest and a fresh one part, so a failed check says what changed. */
function firstDifference(committed, fresh) {
  const a = committed.split("\n");
  const b = fresh.split("\n");
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i += 1;
  let section = "";
  for (let j = Math.min(i, b.length - 1); j >= 0; j -= 1) {
    if (b[j]?.startsWith("## ")) {
      section = b[j];
      break;
    }
  }
  const show = (lines) => lines.slice(i, i + 4).map((line) => `    ${line}`).join("\n");
  return `  first difference at line ${i + 1}${section ? ` (${section})` : ""}:\n` +
    `  committed:\n${show(a)}\n  generated:\n${show(b)}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const { parts, content } = buildDigest();
  if (check) {
    // CI runs this after the CLI build: a help text change must ship with the
    // digest the desktop app hands its agents.
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : null;
    if (current !== content) {
      process.stderr.write(
        `[regen-ade-cli-help] ${path.relative(repoRoot, outPath)} is stale. ` +
          "Run `npm --prefix apps/desktop run regen-cli-help` and commit the result.\n" +
          firstDifference(current ?? "", content),
      );
      process.exitCode = 1;
      return;
    }
    process.stderr.write(`[regen-ade-cli-help] ${path.relative(repoRoot, outPath)} is current\n`);
    return;
  }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outPath, content, "utf8");
  process.stderr.write(`[regen-ade-cli-help] wrote ${outPath} (${parts.length} sections)\n`);
}

try {
  main();
} finally {
  fs.rmSync(isolated.home, { recursive: true, force: true });
}
