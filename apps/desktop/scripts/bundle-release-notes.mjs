import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(appDir, "..", "..");
const targetPath = path.join(appDir, "src", "shared", "bundledReleaseNotes.ts");

const pkg = JSON.parse(await readFile(path.join(appDir, "package.json"), "utf8"));
const version = typeof pkg.version === "string" ? pkg.version.trim().replace(/^v/i, "") : "";
const changelogPath = version ? path.join(repoRoot, "changelog", `v${version}.mdx`) : "";

let markdown = null;
if (changelogPath) {
  try {
    markdown = await readFile(changelogPath, "utf8");
  } catch {
    markdown = null;
  }
}

const source = markdown
  ? `/** Generated by scripts/bundle-release-notes.mjs from changelog/v${version}.mdx. */\nexport const bundledReleaseNotes: { version: string | null; markdown: string | null } = {\n  version: ${JSON.stringify(version)},\n  markdown: ${JSON.stringify(markdown)},\n};\n`
  : `/** Replaced at package time by scripts/bundle-release-notes.mjs when this version has a changelog page. */\nexport const bundledReleaseNotes: { version: string | null; markdown: string | null } = {\n  version: null,\n  markdown: null,\n};\n`;

const current = await readFile(targetPath, "utf8").catch(() => "");
if (current !== source) {
  await writeFile(targetPath, source);
}
