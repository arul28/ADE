import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Bakes this version's release notes, and the few before it, into the app.
 * The after-update "What's new" ends on an "And more" page that lists every
 * version since the one the user updated from, so someone who skipped a few
 * updates still reads what they missed.
 */

/** Versions to carry. Anyone further behind gets these plus a link to the full changelog. */
const HISTORY_LIMIT = 12;

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(appDir, "..", "..");
const changelogDir = path.join(repoRoot, "changelog");
const targetPath = path.join(appDir, "src", "shared", "bundledReleaseNotes.ts");

const pkg = JSON.parse(await readFile(path.join(appDir, "package.json"), "utf8"));
// ADE_RELEASE_NOTES_VERSION previews another version's notes in a dev build.
const version = (process.env.ADE_RELEASE_NOTES_VERSION || (typeof pkg.version === "string" ? pkg.version : "")).trim().replace(/^v/i, "");

function parseVersion(value) {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(value);
  return match ? match.slice(1, 4).map(Number) : null;
}

function compareVersions(a, b) {
  for (let index = 0; index < 3; index += 1) {
    if (a[index] !== b[index]) return a[index] - b[index];
  }
  return 0;
}

const current = parseVersion(version);
let history = [];
if (current) {
  const files = await readdir(changelogDir).catch(() => []);
  const versions = files
    .map((name) => /^v(\d+\.\d+\.\d+)\.mdx$/.exec(name)?.[1])
    .filter((entry) => entry && compareVersions(parseVersion(entry), current) <= 0)
    .sort((a, b) => compareVersions(parseVersion(b), parseVersion(a)))
    .slice(0, HISTORY_LIMIT);
  history = await Promise.all(versions.map(async (entry) => ({
    version: entry,
    markdown: await readFile(path.join(changelogDir, `v${entry}.mdx`), "utf8"),
  })));
}

const own = history.find((entry) => entry.version === version) ?? null;
const header = own
  ? `/** Generated by scripts/bundle-release-notes.mjs from changelog/ (v${version} and the ${history.length - 1} versions before it). */`
  : "/** Replaced at package time by scripts/bundle-release-notes.mjs when this version has a changelog page. */";
const source = `${header}
export type BundledReleaseNotesEntry = { version: string; markdown: string };

export const bundledReleaseNotes: {
  version: string | null;
  markdown: string | null;
  /** This version and the ones before it, newest first. */
  history: BundledReleaseNotesEntry[];
} = {
  version: ${JSON.stringify(own ? version : null)},
  markdown: ${JSON.stringify(own ? own.markdown : null)},
  history: ${JSON.stringify(history, null, 2).replace(/\n/g, "\n  ")},
};
`;

const existing = await readFile(targetPath, "utf8").catch(() => "");
if (existing !== source) {
  await writeFile(targetPath, source);
}
